ACCEPTANCE = {"schema_version": 1,
              "resources": [{"type": "ICON", "id": 101, "file": "assets/icon.ico"}]}


def doc(*resources, **top):
    out = {"schema_version": 1, "resources": list(resources)}
    out.update(top)
    return out


def icon(rid=101, file="assets/icon.ico", **extra):
    return {"type": "ICON", "id": rid, "file": file, **extra}


def lang(primary=9, sub=1):
    return {"primary": primary, "sub": sub}


def version(**extra):
    base = {"type": "VERSIONINFO", "id": 1, "file_version": [1, 2, 3, 4],
            "product_version": [5, 6, 7, 8]}
    base.update(extra)
    return base


def table(strings=None, **extra):
    base = {"language": lang(), "codepage": 1200,
            "strings": strings if strings is not None else {"ProductName": "Example"}}
    base.update(extra)
    return base


def parse(obj):
    return rs.parse_manifest_bytes(json.dumps(obj).encode("utf-8"))


def render(obj):
    return rs.render(parse(obj)).decode("ascii")


def body(text):
    """Rendered text without the five-line header."""
    return text.split("\r\n", 6)[6]


class Base(unittest.TestCase):
    def assertRejected(self, obj_or_bytes, fragment=None, where=None):
        data = obj_or_bytes if isinstance(obj_or_bytes, bytes) else json.dumps(obj_or_bytes).encode()
        with self.assertRaises(rs.ManifestError) as ctx:
            rs.parse_manifest_bytes(data)
        text = "\n".join(f"{w}: {m}" for w, m in ctx.exception.errors)
        if fragment:
            self.assertIn(fragment, text)
        if where:
            self.assertIn(where, [w for w, _m in ctx.exception.errors])
        return text


