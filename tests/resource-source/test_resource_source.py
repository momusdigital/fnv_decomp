class StructureTests(Base):
    def test_unknown_keys(self):
        self.assertRejected(doc(icon(), extra=1), "unknown key 'extra'", "/")
        self.assertRejected(doc(icon(name="x")), "unknown key 'name'", "/resources/0")
        self.assertRejected(doc(icon(language={"primary": 9, "sub": 1, "x": 0})),
                            "unknown key 'x'", "/resources/0/language")
        self.assertRejected(doc(version(string_table=table(extra=1))), "unknown key 'extra'")
        self.assertRejected(doc(version(file="a.ico")), "unknown key 'file'")
        self.assertRejected(doc(icon(file_version=[1, 0, 0, 0])), "unknown key 'file_version'")

    def test_missing_keys(self):
        self.assertRejected({"resources": []}, "missing required key 'schema_version'")
        self.assertRejected({"schema_version": 1}, "missing required key 'resources'")
        self.assertRejected(doc({"type": "ICON", "id": 1}), "missing required key 'file'")
        self.assertRejected(doc({"type": "ICON", "file": "a.ico"}), "missing required key 'id'")
        self.assertRejected(doc({"id": 1, "file": "a.ico"}), "type must be a string")
        self.assertRejected(doc(icon(language={"primary": 9})), "missing required key 'sub'")

    def test_schema_version(self):
        for bad in (2, 0, True, "1", 1.0, None):
            self.assertRejected({"schema_version": bad, "resources": []}, "schema_version")

    def test_wrong_types(self):
        self.assertRejected([], "manifest must be a JSON object")
        self.assertRejected(doc(**{}) | {"resources": {}}, "resources must be a list")
        self.assertRejected(doc("ICON"), "resource must be an object")
        self.assertRejected(doc(icon(file=5)), "file must be a string")
        self.assertRejected(doc(icon(language=9)), "language must be an object")
        self.assertRejected(doc(icon(language=None)), "language must be an object")
        self.assertRejected(doc(icon(type=1)), "type must be a string")

    def test_id_types(self):
        self.assertRejected(doc(icon(rid="101")), "string resource names are not supported")
        self.assertRejected(doc(icon(rid="IDI_APP")), "string resource names are not supported")
        self.assertRejected(doc(icon(rid=True)), "id must be a JSON integer")
        self.assertRejected(b'{"schema_version":1,"resources":[{"type":"ICON","id":101.0,'
                            b'"file":"a.ico"}]}', "id must be a JSON integer")
        self.assertRejected(doc(icon(rid=None)), "id must be a JSON integer")

    def test_id_ranges(self):
        for bad in (0, -1, 65536, 2 ** 40):
            self.assertRejected(doc(icon(rid=bad)), "out of range", "/resources/0/id")
        self.assertRejected(doc({"type": "MANIFEST", "id": 17, "file": "a.manifest"}),
                            "out of range (1..16)")
        self.assertRejected(doc(version(id=0)), "out of range")

    def test_language_ranges(self):
        self.assertRejected(doc(icon(language=lang(0x400, 1))), "primary language is out of range")
        self.assertRejected(doc(icon(language=lang(9, 0x40))), "sublanguage is out of range")
        self.assertRejected(doc(icon(language=lang(-1, 1))), "out of range")
        self.assertRejected(doc(icon(language=lang(True, 1))), "must be a JSON integer")
        self.assertRejected(doc(icon(language=lang("9", 1))), "must be a JSON integer")
        self.assertRejected(doc(icon(), default_language=lang(9, 64)), "sublanguage",
                            "/default_language/sub")

    def test_unsupported_types(self):
        for token in ("BITMAP", "RCDATA", "STRINGTABLE", "24", "RT_MANIFEST", "", "ICON ",
                      "ICON\n", "ICON;", "GROUP_ICON"):
            self.assertRejected(doc(icon(type=token)), "unsupported type")

    def test_non_ascii_type_does_not_case_fold_into_icon(self):
        self.assertEqual("\u0131con".upper(), "ICON")  # dotless i folds in Python
        self.assertRejected(doc(icon(type="\u0131con")), "unsupported type")
        self.assertRejected(doc({"type": "VER\u017fIONINFO", "id": 1, "file_version": [1, 0, 0, 0],
                                 "product_version": [1, 0, 0, 0]}), "unsupported type")

    def test_too_many_resources(self):
        self.assertRejected(doc(*[icon(i, "a.ico") for i in range(1, rs.MAX_RESOURCES + 2)]),
                            f"more than {rs.MAX_RESOURCES} resources")

    def test_errors_are_collected_and_bounded(self):
        resources = [icon(0) for _ in range(rs.MAX_RESOURCES)]
        with self.assertRaises(rs.ManifestError) as ctx:
            parse(doc(*resources))
        self.assertEqual(len(ctx.exception.errors), rs.MAX_REPORTED_ERRORS)


