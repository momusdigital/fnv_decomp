class IsolationTests(CliBase):
    MARKER = "zzreferencedmarkerzz"

    def test_referenced_files_are_never_touched(self):
        manifest = doc(
            icon(101, f"{self.MARKER}/icon.ico"),
            {"type": "MANIFEST", "id": 1, "file": f"{self.MARKER}/app.manifest"},
            version(string_table=table({"OriginalFilename": f"{self.MARKER}.exe"})),
        )
        m = self.write("m.json", manifest)
        target = os.path.join(self.tmp, "out.rc")
        seen = []

        def recorder(real):
            def wrapper(*args, **kwargs):
                seen.append(repr(args))
                return real(*args, **kwargs)
            return wrapper

        names = ["stat", "lstat", "listdir", "scandir", "access", "open", "walk", "readlink"]
        patches = [mock.patch.object(builtins, "open", recorder(builtins.open))]
        patches += [mock.patch.object(os, n, recorder(getattr(os, n))) for n in names
                    if hasattr(os, n)]
        patches += [mock.patch.object(os.path, n, recorder(getattr(os.path, n)))
                    for n in ("exists", "isfile", "isdir", "getsize", "realpath", "lexists")]
        for p in patches:
            p.start()
        try:
            code = rs.main(["render", m, "--out", target], stdout=io.StringIO(),
                           stderr=io.StringIO())
            code2 = rs.main(["validate", m], stdout=io.StringIO(), stderr=io.StringIO())
        finally:
            for p in reversed(patches):
                p.stop()
        self.assertEqual((code, code2), (0, 0))
        self.assertTrue(seen)
        self.assertFalse([s for s in seen if self.MARKER in s])
        self.assertEqual(sorted(os.listdir(self.tmp)), ["m.json", "out.rc"])
        with open(target, "rb") as fh:
            self.assertIn(f'101 ICON "{self.MARKER}/icon.ico"'.encode(), fh.read())

