class DeterminismTests(Base):
    FULL = doc(
        icon(101, "assets/b.ico", language=lang(9, 1)),
        icon(7, "assets/a.ico"),
        {"type": "manifest", "id": 1, "file": "assets/app.manifest", "language": lang(9, 1)},
        version(string_table=table({"ProductName": "P", "CompanyName": "C"}), language=lang(7, 1)),
        icon(101, "assets/c.ico", language=lang(7, 1)),
    )

    def _shuffled(self, obj, rnd):
        if isinstance(obj, dict):
            items = list(obj.items())
            rnd.shuffle(items)
            return {k: self._shuffled(v, rnd) for k, v in items}
        if isinstance(obj, list) and obj and isinstance(obj[0], dict):
            items = [self._shuffled(v, rnd) for v in obj]
            rnd.shuffle(items)
            return items
        return obj

    def test_order_independence(self):
        reference = rs.render(parse(self.FULL))
        rnd = random.Random(1234)
        for _ in range(25):
            self.assertEqual(rs.render(parse(self._shuffled(copy.deepcopy(self.FULL), rnd))),
                             reference)

    def test_whitespace_and_type_case_do_not_matter(self):
        compact = json.dumps(self.FULL, separators=(",", ":")).encode()
        pretty = json.dumps(self.FULL, indent=4).encode()
        upper = copy.deepcopy(self.FULL)
        upper["resources"][2]["type"] = "MANIFEST"
        self.assertEqual(rs.render(rs.parse_manifest_bytes(compact)),
                         rs.render(rs.parse_manifest_bytes(pretty)))
        self.assertEqual(rs.render(parse(upper)), rs.render(parse(self.FULL)))

    def test_repeatable(self):
        outs = {rs.render(parse(self.FULL)) for _ in range(5)}
        self.assertEqual(len(outs), 1)

    def test_line_endings_and_encoding(self):
        data = rs.render(parse(self.FULL))
        data.decode("ascii")
        self.assertTrue(data.endswith(b"\r\n"))
        self.assertNotIn(b"\r\n\r\n\r\n", data)
        self.assertEqual(data.count(b"\n"), data.count(b"\r\n"))
        self.assertEqual(data.count(b"\r"), data.count(b"\r\n"))
        self.assertFalse(data.startswith(b"\xef\xbb\xbf"))

    def test_stable_sort_order(self):
        out = render(self.FULL)
        order = [out.index(s) for s in (
            '7 ICON', "LANGUAGE 0x007", '101 ICON "assets/c.ico"', "1 VERSIONINFO",
            "LANGUAGE 0x009", '101 ICON "assets/b.ico"', '1 24')]
        self.assertEqual(order, sorted(order))

    def test_digest_changes_with_content(self):
        self.assertNotEqual(rs.digest(parse(doc(icon(1)))), rs.digest(parse(doc(icon(2)))))


